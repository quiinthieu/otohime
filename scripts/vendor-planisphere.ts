// Vendors d3-celestial's stars, star names and constellation lines (BSD-3-Clause)
// into app/(planisphere)/_lib/stars.ts, lines.ts and LICENSE.md. Run by hand,
// commit the output; nothing is fetched at runtime.
//   node --experimental-strip-types scripts/vendor-planisphere.ts [ref]
// ref defaults to the current master commit, which is written into the headers.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const REPO = "ofrohn/d3-celestial";
const OUT = resolve(import.meta.dirname, "..", "app", "(planisphere)", "_lib");
const MAG_LIMIT = 4.5;
const COUNT_RANGE = [900, 1000] as const;
const REQUIRED: Record<string, number> = {
  Sirius: 32349,
  Vega: 91262,
  Polaris: 11767,
  Betelgeuse: 27989,
  Canopus: 30438,
  Arcturus: 69673,
  Rigel: 24436,
};

async function get(url: string): Promise<string> {
  const res = await fetch(url, { headers: { "user-agent": "otohime-vendor-planisphere" } });
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

async function resolveRef(ref: string | undefined): Promise<string> {
  if (ref) return ref;
  const commit = JSON.parse(await get(`https://api.github.com/repos/${REPO}/commits/master`)) as { sha: string };
  return commit.sha;
}

// d3-celestial longitudes run [-180, 180]; right ascension in degrees is [0, 360).
const ra = (lon: number) => (((lon % 360) + 360) % 360);
const fixed = (n: number) => Number(n.toFixed(4));

type StarFeature = { id: number; properties: { mag: number }; geometry: { coordinates: [number, number] } };
type LineFeature = { id: string; properties: { rank: string }; geometry: { coordinates: [number, number][][] } };

const ref = await resolveRef(process.argv[2]);
const raw = `https://raw.githubusercontent.com/${REPO}/${ref}`;
const stars = JSON.parse(await get(`${raw}/data/stars.6.json`)) as { features: StarFeature[] };
const names = JSON.parse(await get(`${raw}/data/starnames.json`)) as Record<string, { name?: string }>;
const lines = JSON.parse(await get(`${raw}/data/constellations.lines.json`)) as { features: LineFeature[] };
const licence = await get(`${raw}/LICENSE`);

const kept = stars.features
  .filter((f) => f.properties.mag <= MAG_LIMIT)
  .map((f) => {
    const [lon, lat] = f.geometry.coordinates;
    const name = names[String(f.id)]?.name?.trim();
    const row: [number, number, number, number, string?] = [f.id, fixed(ra(lon)), fixed(lat), f.properties.mag];
    if (name) row.push(name);
    return row;
  })
  .sort((a, b) => a[3] - b[3] || a[0] - b[0]);

if (kept.length < COUNT_RANGE[0] || kept.length > COUNT_RANGE[1]) {
  throw new Error(`expected ${COUNT_RANGE[0]}-${COUNT_RANGE[1]} stars at mag <= ${MAG_LIMIT}, got ${kept.length}`);
}
for (const [name, hip] of Object.entries(REQUIRED)) {
  if (!kept.some((s) => s[0] === hip)) throw new Error(`missing ${name} (HIP ${hip})`);
}

const header = (what: string) => `// GENERATED by scripts/vendor-planisphere.ts from https://github.com/${REPO}
// at ${ref}. Do not edit by hand; rerun the script.
// ${what}
// d3-celestial is BSD-3-Clause, see ./LICENSE.md.
`;

const starsTs = `${header(
  `Stars: XHIP (Anderson & Francis 2012, VizieR V/137D) via data/stars.6.json, magnitude ${MAG_LIMIT} or brighter;
// names from data/starnames.json. RA is in degrees [0, 360), J2000.`,
)}
/** [hip, ra, dec, mag, name?] */
export type Star = readonly [hip: number, ra: number, dec: number, mag: number, name?: string];

export const STARS: readonly Star[] = [
${kept.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
];
`;

const features = lines.features;
const segments = features.reduce((n, f) => n + f.geometry.coordinates.length, 0);
const linesBody = features
  .map((f) => {
    const segs = f.geometry.coordinates.map((poly) => poly.map(([lon, lat]) => [fixed(ra(lon)), fixed(lat)]));
    return `  { id: ${JSON.stringify(f.id)}, rank: ${Number(f.properties.rank)}, segments: ${JSON.stringify(segs)} },`;
  })
  .join("\n");

const linesTs = `${header("Constellation lines after the IAU, data/constellations.lines.json. RA is in degrees [0, 360), J2000.")}
export const LINES: readonly {
  id: string;
  rank: 1 | 2 | 3;
  segments: readonly (readonly (readonly [number, number])[])[];
}[] = [
${linesBody}
];
`;

const licenceMd = `<!-- Vendored by scripts/vendor-planisphere.ts from https://github.com/${REPO} at ${ref}.
     Covers stars.ts and lines.ts (data/stars.6.json, data/starnames.json,
     data/constellations.lines.json). Upstream sources: XHIP (VizieR V/137D),
     IAU constellation lines. -->

${licence}`;

writeFileSync(join(OUT, "stars.ts"), starsTs);
writeFileSync(join(OUT, "lines.ts"), linesTs);
writeFileSync(join(OUT, "LICENSE.md"), licenceMd);
console.log(`wrote ${kept.length} stars and ${features.length} constellations (${segments} polylines) from ${REPO}@${ref} to ${OUT}`);
