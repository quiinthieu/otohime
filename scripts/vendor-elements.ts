// Vendors Bowserinator's Periodic-Table-JSON (CC BY-SA 3.0) into
// app/(elements)/_lib/elements.ts and LICENSE.md. Run by hand, commit the output;
// nothing is fetched at runtime.
//   node --experimental-strip-types scripts/vendor-elements.ts [ref]
// ref defaults to the current master commit, which is written into the header.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const REPO = "Bowserinator/Periodic-Table-JSON";
const OUT = resolve(import.meta.dirname, "..", "app", "(elements)", "_lib");

const FIELDS = [
  "number",
  "symbol",
  "name",
  "category",
  "xpos",
  "ypos",
  "atomic_mass",
  "phase",
  "melt",
  "boil",
  "shells",
  "electron_configuration",
  "electron_configuration_semantic",
  "discovered_by",
  "summary",
  "source",
  "bohr_model_3d",
] as const;

async function get(url: string): Promise<string> {
  const res = await fetch(url, { headers: { "user-agent": "otohime-vendor-elements" } });
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

async function resolveRef(ref: string | undefined): Promise<string> {
  if (ref) return ref;
  const commit = JSON.parse(await get(`https://api.github.com/repos/${REPO}/commits/master`)) as { sha: string };
  return commit.sha;
}

const ref = await resolveRef(process.argv[2]);
const raw = `https://raw.githubusercontent.com/${REPO}/${ref}`;
const data = JSON.parse(await get(`${raw}/PeriodicTableJSON.json`)) as { elements: Record<string, unknown>[] };
const licence = await get(`${raw}/LICENSE.md`);

const kept = data.elements
  .filter((e) => typeof e.number === "number" && e.number <= 118)
  .sort((a, b) => (a.number as number) - (b.number as number))
  .map((e) => Object.fromEntries(FIELDS.map((f) => [f, e[f] ?? null])));
if (kept.length !== 118) throw new Error(`expected 118 elements, got ${kept.length}`);

const body = kept.map((e) => `  ${JSON.stringify(e)},`).join("\n");
const ts = `// GENERATED by scripts/vendor-elements.ts from https://github.com/${REPO}
// at ${ref}. Do not edit by hand; rerun the script.
// The summaries are Wikipedia text: CC BY-SA 3.0, see ./LICENSE.md.

export type Phase = "Gas" | "Liquid" | "Solid";

export interface Element {
  number: number;
  symbol: string;
  name: string;
  category: string;
  xpos: number;
  ypos: number;
  atomic_mass: number;
  phase: Phase;
  /** kelvin */
  melt: number | null;
  /** kelvin */
  boil: number | null;
  shells: number[];
  electron_configuration: string;
  electron_configuration_semantic: string;
  discovered_by: string | null;
  summary: string;
  source: string;
  bohr_model_3d: string | null;
}

export const ELEMENTS: readonly Element[] = [
${body}
];
`;

writeFileSync(join(OUT, "elements.ts"), ts);
writeFileSync(join(OUT, "LICENSE.md"), licence);
console.log(`wrote ${kept.length} elements from ${REPO}@${ref} to ${OUT}`);
