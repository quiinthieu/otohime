// The vendored dataset: 118 elements in order, sane fields, and its licence beside it.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { RAW_CATEGORIES } from "./categories.ts";
import { ELEMENTS } from "./elements.ts";

test("exactly 118 elements, numbered 1..118 in order, no element 119", () => {
  assert.equal(ELEMENTS.length, 118);
  ELEMENTS.forEach((el, i) => assert.equal(el.number, i + 1, `index ${i} holds ${el.number}`));
  assert.ok(!ELEMENTS.some((el) => el.number > 118));
});

test("symbols and names are unique and non-empty", () => {
  for (const key of ["symbol", "name"] as const) {
    const values = ELEMENTS.map((el) => el[key]);
    assert.ok(values.every((v) => typeof v === "string" && v.length > 0), key);
    assert.equal(new Set(values).size, 118, `${key} repeats`);
  }
  assert.ok(ELEMENTS.every((el) => /^[A-Z][a-z]{0,2}$/.test(el.symbol)));
});

test("every source is a Wikipedia article", () => {
  for (const el of ELEMENTS) assert.ok(el.source.startsWith("https://en.wikipedia.org/"), `${el.symbol}: ${el.source}`);
});

test("shells sum to the atomic number, at most seven of them", () => {
  for (const el of ELEMENTS) {
    assert.equal(
      el.shells.reduce((a, b) => a + b, 0),
      el.number,
      `${el.symbol} shells ${el.shells.join(",")}`,
    );
    assert.ok(el.shells.length >= 1 && el.shells.length <= 7, el.symbol);
    assert.ok(el.shells.every((s) => Number.isInteger(s) && s > 0), el.symbol);
  }
});

test("every raw category maps to a legend category", () => {
  for (const el of ELEMENTS) assert.ok(RAW_CATEGORIES[el.category], `${el.symbol}: ${el.category}`);
});

test("numbers are numbers and nulls are only where upstream has none", () => {
  for (const el of ELEMENTS) {
    assert.ok(Number.isFinite(el.atomic_mass) && el.atomic_mass > 0, el.symbol);
    assert.ok(["Gas", "Liquid", "Solid"].includes(el.phase), el.symbol);
    for (const k of ["melt", "boil"] as const) assert.ok(el[k] === null || (Number.isFinite(el[k]) && el[k] > 0), `${el.symbol} ${k}`);
    assert.ok(el.summary.length > 0 && el.electron_configuration.length > 0, el.symbol);
  }
  // known gaps upstream: aluminium has no discoverer, the superheavies no melting point
  assert.equal(ELEMENTS[12].discovered_by, null);
  assert.equal(ELEMENTS[117].melt, null);
});

test("positions are unique and the rows hold 2, 8, 8, 18, 18, 17, 17, 0, 15, 15", () => {
  const cells = ELEMENTS.map((el) => `${el.xpos},${el.ypos}`);
  assert.equal(new Set(cells).size, 118);
  const rows = Array.from({ length: 10 }, (_, i) => ELEMENTS.filter((el) => el.ypos === i + 1).length);
  assert.deepEqual(rows, [2, 8, 8, 18, 18, 17, 17, 0, 15, 15]);
  assert.ok(ELEMENTS.every((el) => el.xpos >= 1 && el.xpos <= 18));
});

test("the CC BY-SA licence sits beside the data", () => {
  const licence = readFileSync(join(import.meta.dirname, "LICENSE.md"), "utf8");
  assert.match(licence, /Attribution-ShareAlike/);
  assert.match(readFileSync(join(import.meta.dirname, "elements.ts"), "utf8"), /GENERATED by scripts\/vendor-elements\.ts/);
});
