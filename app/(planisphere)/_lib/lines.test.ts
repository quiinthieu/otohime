import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { LINES } from "./lines.ts";

test("89 constellations and 150 polylines", () => {
  assert.equal(LINES.length, 89);
  assert.equal(LINES.reduce((n, l) => n + l.segments.length, 0), 150);
});

test("ids are three-letter IAU codes (Serpens is two features) and ranks are 1 to 3", () => {
  assert.equal(new Set(LINES.map((l) => l.id)).size, 88);
  assert.equal(LINES.filter((l) => l.id === "Ser").length, 2);
  for (const l of LINES) {
    assert.match(l.id, /^[A-Z][A-Za-z]{2}$/, l.id);
    assert.ok(l.rank === 1 || l.rank === 2 || l.rank === 3, `${l.id} rank ${l.rank}`);
  }
});

test("every polyline has two or more points, all in range", () => {
  for (const l of LINES) {
    for (const poly of l.segments) {
      assert.ok(poly.length >= 2, l.id);
      for (const [ra, dec] of poly) {
        assert.ok(Number.isFinite(ra) && ra >= 0 && ra < 360, `${l.id} ra ${ra}`);
        assert.ok(Number.isFinite(dec) && dec >= -90 && dec <= 90, `${l.id} dec ${dec}`);
      }
    }
  }
});

test("Orion, Ursa Major and Crux are there", () => {
  for (const id of ["Ori", "UMa", "Cru", "Sco", "Cas"]) assert.ok(LINES.some((l) => l.id === id), id);
});

test("the generated header names the ref and has no import", () => {
  const text = readFileSync(new URL("./lines.ts", import.meta.url), "utf8");
  assert.match(text, /^\/\/ GENERATED by scripts\/vendor-planisphere\.ts from https:\/\/github\.com\/ofrohn\/d3-celestial\n\/\/ at [0-9a-f]{40}\./);
  assert.doesNotMatch(text, /^\s*import\s/m);
});
