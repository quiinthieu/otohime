import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { STARS } from "./stars.ts";

const REF = "7e720a3de062059d4c5400a379146a601d9010e0";
const byHip = (hip: number) => STARS.find((s) => s[0] === hip);
const near = (a: number, b: number, tol: number, what = "") => assert.ok(Math.abs(a - b) <= tol, `${what}: ${a} vs ${b}`);

test("exactly 921 stars at the committed ref", () => {
  assert.equal(STARS.length, 921);
});

test("every star has an id, RA in [0, 360), Dec in [-90, 90] and magnitude 4.5 or brighter", () => {
  for (const [hip, ra, dec, mag, name] of STARS) {
    assert.ok(Number.isInteger(hip) && hip > 0, `${hip}`);
    assert.ok(Number.isFinite(ra) && ra >= 0 && ra < 360, `${hip} ra ${ra}`);
    assert.ok(Number.isFinite(dec) && dec >= -90 && dec <= 90, `${hip} dec ${dec}`);
    assert.ok(Number.isFinite(mag) && mag <= 4.5, `${hip} mag ${mag}`);
    assert.ok(name === undefined || (typeof name === "string" && name.length > 0), `${hip} name`);
  }
});

test("HIP ids are unique and the list runs brightest first", () => {
  assert.equal(new Set(STARS.map((s) => s[0])).size, STARS.length);
  for (let i = 1; i < STARS.length; i++) assert.ok(STARS[i - 1][3] <= STARS[i][3], `row ${i}`);
});

test("the seven named stars are present", () => {
  const named: [number, string][] = [
    [32349, "Sirius"],
    [91262, "Vega"],
    [11767, "Polaris"],
    [27989, "Betelgeuse"],
    [30438, "Canopus"],
    [69673, "Arcturus"],
    [24436, "Rigel"],
  ];
  for (const [hip, name] of named) assert.equal(byHip(hip)?.[4], name, name);
});

test("Polaris is at Dec 89.26", () => {
  near(byHip(11767)![2], 89.26, 0.01, "Dec");
});

test("the vendored Polaris, Sirius and Vega match the J2000 literals of the sky tests within 0.01 degree", () => {
  const literals: [number, number, number][] = [
    [11767, 37.9546, 89.2641],
    [32349, 101.2872, -16.7161],
    [91262, 279.2347, 38.7837],
  ];
  for (const [hip, ra, dec] of literals) {
    near(byHip(hip)![1], ra, 0.01, `${hip} ra`);
    near(byHip(hip)![2], dec, 0.01, `${hip} dec`);
  }
});

test("Sirius is the brightest and has a name; plenty of stars are named", () => {
  assert.equal(STARS[0][4], "Sirius");
  assert.ok(STARS.filter((s) => s[4]).length > 60);
});

test("the generated header names the d3-celestial ref and has no import", () => {
  const text = readFileSync(new URL("./stars.ts", import.meta.url), "utf8");
  assert.match(text, /^\/\/ GENERATED by scripts\/vendor-planisphere\.ts from https:\/\/github\.com\/ofrohn\/d3-celestial\n\/\/ at [0-9a-f]{40}\./);
  assert.ok(text.includes(`at ${REF}.`));
  assert.doesNotMatch(text, /^\s*import\s/m);
});
