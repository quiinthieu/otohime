import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright-core';
const base = process.env.BASE_URL || 'https://otohime.dev';
mkdirSync('.agent-artifacts/pm-268-t-1600-qa', { recursive: true });
const health = async () => { const r = await fetch(`${base}/api/health`); assert.equal(r.status, 200); return (await r.json()).sha; };
const before = await health();
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', env: { ...process.env, TMPDIR: '/tmp' } });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base, { waitUntil: 'load' });
  const pocket = page.getByRole('region', { name: 'Pocket console', exact: true });
  const group = pocket.getByRole('group', { name: 'Print run', exact: true });
  await group.waitFor({ state: 'visible' });
  assert.deepEqual(await group.getByRole('radio').evaluateAll(rs => rs.map(r => r.closest('label')?.textContent?.trim())), ['House', 'Sumi black', 'Riso pink + mint', 'Indigo night']);
  const indigo = group.getByRole('radio', { name: 'Indigo night', exact: true });
  await group.getByText('Indigo night', { exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.printRun === 'indigo');
  assert.equal(await page.evaluate(() => localStorage.getItem('otohime:print-run:v1')), 'indigo');
  await page.screenshot({ path: '.agent-artifacts/pm-268-t-1600-qa/pocket-phone.png' });
  await page.reload({ waitUntil: 'load' });
  await page.waitForFunction(() => document.documentElement.dataset.printRun === 'indigo' && [...document.querySelectorAll('[data-print-run-switch] input[value=indigo]')].every(r => r.checked));
  assert.equal(await indigo.isChecked(), true);
  await indigo.focus();
  await page.keyboard.press('Control+k');
  const dialog = page.locator('dialog.pocket-terminal');
  await dialog.waitFor({ state: 'visible' });
  const field = page.locator('#pt-in');
  await field.fill('print run');
  await field.press('Enter');
  assert.match(await dialog.getByRole('log').textContent(), /Indigo night \(indigo\)/);
  await field.fill('print run purple');
  await field.press('Enter');
  assert.equal(await page.evaluate(() => localStorage.getItem('otohime:print-run:v1')), 'indigo');
  await dialog.getByRole('group', { name: 'Print run', exact: true }).getByText('Sumi black', { exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.printRun === 'sumi');
  assert.equal(await group.getByRole('radio', { name: 'Sumi black', exact: true }).isChecked(), true);
  await field.fill('print run indigo');
  await field.press('Enter');
  await page.waitForFunction(() => document.documentElement.dataset.printRun === 'indigo');
  assert.equal(await indigo.isChecked(), true);
  await dialog.screenshot({ path: '.agent-artifacts/pm-268-t-1600-qa/terminal-phone.png' });
  await page.keyboard.press('Escape');
  assert.equal(await indigo.evaluate(el => el === document.activeElement), true);
  await page.setViewportSize({ width: 1366, height: 768 });
  const bounds = await group.boundingBox();
  assert.ok(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 1366);
  await page.screenshot({ path: '.agent-artifacts/pm-268-t-1600-qa/pocket-desktop.png' });
  assert.deepEqual(errors, []);
  const after = await health();
  assert.equal(after, before, 'deployment did not change during probe');
  console.log(JSON.stringify({ pass: true, deployed_sha: after, browser: await browser.version(), checks: ['visible labels', 'pointer select', 'storage', 'reload', 'command read', 'invalid-id negative control', 'focus return', 'page errors', 'desktop reflow', 'control-command sync'], screenshots: 3 }));
  await context.close();
} finally { await browser.close(); }
